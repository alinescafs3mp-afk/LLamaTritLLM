def multi_rows(items, split):
    for i,(u1,a1,u2,a2) in enumerate(items):
        yield {'messages':[{'role':'user','content':u1},{'role':'assistant','content':a1},{'role':'user','content':u2},{'role':'assistant','content':a2}], 'family':f'{split}_context_{i:03}', 'split':split, 'origin':'authored-synthetic-v2'}

def identity(row):
    if 'messages' in row: x=row['messages']
    elif 'text' in row: x=row['text']
    else: x=[row['prompt'],row['answer']]
    return hashlib.sha256(json.dumps(x,ensure_ascii=False,sort_keys=True).encode()).hexdigest()

def run():
    train=parse(TRAIN,'train')+list(multi_rows(MULTI,'train'))
    train += [{'text':x,'family':f'pretrain_{i:03}','split':'train','origin':'authored-synthetic-v2'} for i,x in enumerate(TEXTS.strip().splitlines())]
    validation=parse(VALIDATION,'validation')+list(multi_rows(VAL_MULTI,'validation'))
    test=parse(TEST,'test')+list(multi_rows(TEST_MULTI,'test'))
    seen=set(); counts={}; records={}
    for name, rows in [('seed',train),('validation',validation),('test',test)]:
        for row in rows:
            ident=identity(row)
            assert ident not in seen, f'duplicate example {row}'
            seen.add(ident);row['id']='ru-v2-'+ident[:20]
        target=ROOT/'data'/f'{name}.jsonl'
        target.write_text(''.join(json.dumps(row,ensure_ascii=False)+'\n' for row in rows),encoding='utf-8')
        counts[name]=len(rows)
        records[name]={'count':len(rows),'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'bytes':target.stat().st_size}
    manifest={'version':'conversation-ru-v2','language':'ru','origin':'original authored synthetic text, not scraped, not private user conversations','license':'MIT (same as application)','counts':counts,'files':records,'blind_test':'test.jsonl is NEVER loaded by trainer automatically','claim':'starter corpus; no universal fluency or factual accuracy guarantee','generation':'python3 tools/build_conversation_dataset.py','evolution':'Keep blind test families frozen. New audits add reviewed train families and log validation changes.'}
    (ROOT/'data'/'DATASET_MANIFEST.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(counts))
if __name__=='__main__': run()
