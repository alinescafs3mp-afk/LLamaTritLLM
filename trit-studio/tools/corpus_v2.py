def parse(block, split):
    rows=[]; family=''
    for line in block.strip().splitlines():
        if not line.strip(): continue
        if line.startswith('['): family=line[1:-1];continue
        prompt, answer=line.split('|',1)
        rows.append({'prompt':prompt,'answer':answer.replace('\\n','\n'),'family':family,'split':split,'origin':'authored-synthetic-v2'})
    return rows

